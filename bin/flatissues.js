#!/usr/bin/env node

/**
 * flatissues — dead-simple file-based issue tracking.
 *
 * Subcommands:
 *   init [--dir issues] [--project-name "Name"] [--inline] [--force]
 *     Default: scaffold ./<dir>/ (if absent or empty) and write
 *     ./.claude/rules/flatissues.md (always refreshed). The rule file is
 *     auto-loaded by Claude Code at session start.
 *
 *     --inline: write the snippet into ./CLAUDE.md (between idempotency
 *     markers) instead of the rule file.
 *
 *     --force: overwrite an existing non-empty ./<dir>/ (re-scaffolds
 *     templates including config.json — your customizations there will
 *     be lost).
 *
 *   help
 *     Show usage.
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const PACKAGE_ROOT = path.resolve(__dirname, '..');
const TEMPLATE_DIR = path.join(PACKAGE_ROOT, 'template', 'issues');
const SNIPPET_FILE = path.join(PACKAGE_ROOT, 'CLAUDE.md.snippet');

const RULE_HEADER = '<!-- Generated by flatissues — do not edit; run `npx flatissues init` to refresh -->\n\n';
const INLINE_START = '<!-- flatissues:start (managed block — re-run `npx flatissues init --inline` to update) -->';
const INLINE_END = '<!-- flatissues:end -->';
const INLINE_BLOCK_RE = /<!-- flatissues:start[^>]*-->[\s\S]*?<!-- flatissues:end -->\n?/g;

// Known flag schema. value:true means the flag consumes the next arg.
const INIT_FLAGS = {
  'dir': { value: true },
  'project-name': { value: true },
  'inline': { value: false },
  'force': { value: false }
};

function parseArgs(argv, flagSchema) {
  const args = { _: [], flags: {} };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) {
      args._.push(a);
      continue;
    }
    const eqIdx = a.indexOf('=');
    let key, value;
    if (eqIdx !== -1) {
      key = a.slice(2, eqIdx);
      value = a.slice(eqIdx + 1);
    } else {
      key = a.slice(2);
      value = undefined;
    }
    if (flagSchema && !(key in flagSchema)) {
      console.error(`Error: unknown flag --${key}`);
      console.error(`  Run \`flatissues help\` for usage.`);
      process.exit(1);
    }
    const expectsValue = flagSchema ? flagSchema[key].value : false;
    if (expectsValue) {
      if (value !== undefined) {
        args.flags[key] = value;
      } else {
        const next = argv[i + 1];
        if (next === undefined || next.startsWith('--')) {
          console.error(`Error: --${key} requires a value`);
          process.exit(1);
        }
        args.flags[key] = next;
        i++;
      }
    } else {
      if (value !== undefined) {
        console.error(`Error: --${key} does not take a value (got =${value})`);
        process.exit(1);
      }
      args.flags[key] = true;
    }
  }
  return args;
}

function copyDirSync(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirSync(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  }
}

function substituteInFile(filepath, replacements) {
  let content = fs.readFileSync(filepath, 'utf-8');
  let changed = false;
  for (const [key, value] of Object.entries(replacements)) {
    const token = `{{${key}}}`;
    if (content.includes(token)) {
      content = content.split(token).join(value);
      changed = true;
    }
  }
  if (changed) fs.writeFileSync(filepath, content);
}

function substituteInString(content, replacements) {
  for (const [key, value] of Object.entries(replacements)) {
    const token = `{{${key}}}`;
    content = content.split(token).join(value);
  }
  return content;
}

function readSnippet(replacements) {
  const raw = fs.readFileSync(SNIPPET_FILE, 'utf-8');
  return replacements ? substituteInString(raw, replacements) : raw;
}

function writeRuleFile(rootDir, dirName) {
  const ruleDir = path.join(rootDir, '.claude', 'rules');
  fs.mkdirSync(ruleDir, { recursive: true });
  const rulePath = path.join(ruleDir, 'flatissues.md');
  const snippet = readSnippet({ dirName });
  fs.writeFileSync(rulePath, RULE_HEADER + snippet);
  return path.relative(rootDir, rulePath);
}

function writeInlineToClaudeMd(rootDir, dirName) {
  const claudeMdPath = path.join(rootDir, 'CLAUDE.md');
  const snippet = readSnippet({ dirName });
  const block = `${INLINE_START}\n${snippet}${INLINE_END}\n`;

  let body = '';
  let action;
  if (fs.existsSync(claudeMdPath)) {
    body = fs.readFileSync(claudeMdPath, 'utf-8');
    const stripped = body.replace(INLINE_BLOCK_RE, '');
    if (stripped !== body) {
      action = 'replaced flatissues block in CLAUDE.md';
    } else {
      action = 'appended flatissues block to CLAUDE.md';
    }
    body = stripped.replace(/\s+$/, '') + '\n\n';
  } else {
    action = 'created CLAUDE.md with flatissues block';
  }

  fs.writeFileSync(claudeMdPath, body + block);
  return { relPath: 'CLAUDE.md', action };
}

function validateProjectName(name) {
  if (/["\\]/.test(name)) {
    console.error(`Error: --project-name cannot contain " or \\ characters.`);
    console.error(`  Got: ${JSON.stringify(name)}`);
    process.exit(1);
  }
}

function validateDirName(dirName) {
  if (path.isAbsolute(dirName)) {
    console.error(`Error: --dir must be a directory name, not an absolute path.`);
    console.error(`  Got: ${dirName}`);
    process.exit(1);
  }
  if (/[\\/]/.test(dirName) || dirName.split(path.sep).some(p => p === '..')) {
    console.error(`Error: --dir must be a single directory name (no slashes, no ..).`);
    console.error(`  Got: ${dirName}`);
    process.exit(1);
  }
  if (dirName === '' || dirName === '.') {
    console.error(`Error: --dir must be a non-empty directory name.`);
    process.exit(1);
  }
}

function cmdInit(args) {
  const rootDir = process.cwd();
  const dirName = args.flags.dir || 'issues';
  const projectName = args.flags['project-name'] || path.basename(rootDir);
  const inline = !!args.flags.inline;
  const force = !!args.flags.force;

  validateDirName(dirName);
  validateProjectName(projectName);

  const targetDir = path.resolve(rootDir, dirName);

  let issuesAction;
  const dirExists = fs.existsSync(targetDir);
  const dirNonEmpty = dirExists &&
    fs.readdirSync(targetDir).filter(f => !f.startsWith('.')).length > 0;

  if (dirNonEmpty && !force) {
    issuesAction = 'left as-is (use --force to re-scaffold)';
  } else {
    copyDirSync(TEMPLATE_DIR, targetDir);
    const replacements = { projectName, dirName };
    substituteInFile(path.join(targetDir, 'config.json'), replacements);
    substituteInFile(path.join(targetDir, 'README.md'), replacements);
    substituteInFile(path.join(targetDir, 'ISSUE_TEMPLATE.md'), replacements);
    substituteInFile(path.join(targetDir, 'update-index.js'), replacements);

    try {
      execFileSync(process.execPath, [path.join(targetDir, 'update-index.js')], {
        stdio: ['ignore', 'ignore', 'inherit']
      });
    } catch (err) {
      console.error(`Warning: failed to generate initial INDEX.md (${err.message})`);
      console.error(`  Run \`node ${dirName}/update-index.js\` manually.`);
    }

    issuesAction = dirNonEmpty
      ? `re-scaffolded (project: "${projectName}", --force)`
      : `your tracker (project: "${projectName}")`;
  }

  let claudeOutput;
  if (inline) {
    claudeOutput = writeInlineToClaudeMd(rootDir, dirName);
  } else {
    const relPath = writeRuleFile(rootDir, dirName);
    claudeOutput = { relPath, action: 'auto-loaded by Claude Code at next session start' };
  }

  const pad = (label, width) => label + ' '.repeat(Math.max(1, width - label.length));
  console.log(`flatissues: ready`);
  console.log(`  ${pad(`${dirName}/`, 30)}— ${issuesAction}`);
  if (!dirNonEmpty || force) {
    console.log(`  ${pad(`${dirName}/INDEX.md`, 30)}— initial index (empty)`);
  }
  console.log(`  ${pad(claudeOutput.relPath, 30)}— ${claudeOutput.action}`);
  console.log('');
  if (!inline) {
    console.log(`If running this in an active Claude Code session, read`);
    console.log(`${claudeOutput.relPath} now to load the convention for this session.`);
    console.log(`(Otherwise it will be auto-loaded on next session start.)`);
  } else {
    console.log(`If running this in an active Claude Code session, re-read CLAUDE.md`);
    console.log(`to pick up the new flatissues block for this session.`);
  }
}

function cmdHelp() {
  console.log(`flatissues — file-based issue tracking that lives in your repo.

Usage:
  flatissues init [options]    Scaffold ./issues/ and register it with Claude Code
  flatissues help              Show this help

Options for init:
  --dir <name>             Target directory name (default: issues)
  --project-name <name>    Project name shown in INDEX.md (default: current dir)
  --inline                 Append snippet to ./CLAUDE.md instead of writing
                           ./.claude/rules/flatissues.md (the default)
  --force                  Re-scaffold an existing non-empty issues/ dir
                           (overwrites config.json — customizations lost)

The Claude rule file (or inline block) is always refreshed; --force only
controls whether the issues/ scaffolding is re-written.

Examples:
  npx flatissues init
  npx flatissues init --project-name "My App"
  npx flatissues init --inline
  npx flatissues init --dir tickets
`);
}

function main() {
  const argv = process.argv.slice(2);
  const cmd = argv[0];

  switch (cmd) {
    case 'init': {
      const args = parseArgs(argv.slice(1), INIT_FLAGS);
      if (args._.length > 0) {
        console.error(`Error: unexpected positional argument: ${args._[0]}`);
        process.exit(1);
      }
      cmdInit(args);
      break;
    }
    case 'help':
    case '--help':
    case '-h':
    case undefined:
      cmdHelp();
      break;
    default:
      console.error(`Unknown command: ${cmd}`);
      console.error('Run `flatissues help` for usage.');
      process.exit(1);
  }
}

main();
